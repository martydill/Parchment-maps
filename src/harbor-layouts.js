const oval = (u, v, rx, ry, sides = 12) =>
  Array.from({ length: sides }, (_, i) => {
    const angle = (i / sides) * Math.PI * 2;
    return [u + Math.cos(angle) * rx, v + Math.sin(angle) * ry];
  });
const ground = (outline, z = 5) => ({ outline, z });
